import argparse
import json
from pathlib import Path

import numpy as np
import torch
import torch.nn as nn
from PIL import Image
from scipy import linalg
from torch.utils.data import DataLoader, Dataset
from torchvision import models, transforms


IMAGE_EXTENSIONS = {".png", ".jpg", ".jpeg", ".bmp", ".webp"}


def parse_args():
    parser = argparse.ArgumentParser(
        description="Compute FID and optional LPIPS metrics for base Stable Diffusion and LoRA generated images."
    )
    parser.add_argument("--reference_dir", required=True, help="Directory of real/reference images, used by FID.")
    parser.add_argument("--base_dir", required=True, help="Directory of images generated by the unfine-tuned base model.")
    parser.add_argument("--lora_dir", required=True, help="Directory of images generated by the LoRA fine-tuned model.")
    parser.add_argument("--output_dir", default="results", help="Directory for JSON and Markdown reports.")
    parser.add_argument("--batch_size", type=int, default=8)
    parser.add_argument("--device", default="auto", choices=["auto", "cpu", "cuda"])
    parser.add_argument("--skip_fid", action="store_true", help="Skip FID calculation.")
    parser.add_argument("--enable_lpips", action="store_true", help="Compute LPIPS if the lpips package is installed.")
    parser.add_argument(
        "--lpips_reference_dir",
        help=(
            "Optional paired reference directory for LPIPS. If omitted, LPIPS is computed between base and LoRA "
            "outputs with sorted filename pairing, which measures perceptual change rather than image quality."
        ),
    )
    return parser.parse_args()


def resolve_dir(path_str):
    path = Path(path_str).expanduser().resolve()
    if not path.exists() or not path.is_dir():
        raise FileNotFoundError(f"Directory not found: {path}")
    return path


def list_images(image_dir):
    files = sorted(p for p in Path(image_dir).rglob("*") if p.suffix.lower() in IMAGE_EXTENSIONS)
    if not files:
        raise ValueError(f"No image files found in: {image_dir}")
    return files


class ImagePathDataset(Dataset):
    def __init__(self, image_paths, transform):
        self.image_paths = list(image_paths)
        self.transform = transform

    def __len__(self):
        return len(self.image_paths)

    def __getitem__(self, index):
        image = Image.open(self.image_paths[index]).convert("RGB")
        return self.transform(image)


def choose_device(device_arg):
    if device_arg == "cuda":
        if not torch.cuda.is_available():
            raise RuntimeError("CUDA was requested, but torch.cuda.is_available() is False.")
        return torch.device("cuda")
    if device_arg == "cpu":
        return torch.device("cpu")
    return torch.device("cuda" if torch.cuda.is_available() else "cpu")


def build_inception_model(device):
    weights = models.Inception_V3_Weights.IMAGENET1K_V1
    model = models.inception_v3(weights=weights)
    model.fc = nn.Identity()
    model.eval().to(device)
    return model


def inception_transform():
    return transforms.Compose(
        [
            transforms.Resize((299, 299), interpolation=transforms.InterpolationMode.BILINEAR),
            transforms.ToTensor(),
            transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225]),
        ]
    )


@torch.no_grad()
def extract_inception_features(image_paths, model, device, batch_size):
    dataset = ImagePathDataset(image_paths, inception_transform())
    loader = DataLoader(dataset, batch_size=batch_size, shuffle=False, num_workers=0)
    features = []
    for batch in loader:
        batch = batch.to(device)
        output = model(batch)
        if isinstance(output, tuple):
            output = output[0]
        features.append(output.detach().cpu().numpy())
    return np.concatenate(features, axis=0).astype(np.float64)


def calculate_stats(features):
    if features.shape[0] < 2:
        raise ValueError("FID needs at least two images in each directory to estimate covariance.")
    mean = np.mean(features, axis=0)
    cov = np.cov(features, rowvar=False)
    return mean, cov


def calculate_fid(features_a, features_b):
    mean_a, cov_a = calculate_stats(features_a)
    mean_b, cov_b = calculate_stats(features_b)
    mean_diff = mean_a - mean_b
    cov_sqrt, _ = linalg.sqrtm(cov_a.dot(cov_b), disp=False)

    if not np.isfinite(cov_sqrt).all():
        offset = np.eye(cov_a.shape[0]) * 1e-6
        cov_sqrt = linalg.sqrtm((cov_a + offset).dot(cov_b + offset))

    if np.iscomplexobj(cov_sqrt):
        cov_sqrt = cov_sqrt.real

    fid = mean_diff.dot(mean_diff) + np.trace(cov_a + cov_b - 2.0 * cov_sqrt)
    return float(fid)


def pil_to_lpips_tensor(path):
    transform = transforms.Compose(
        [
            transforms.Resize((256, 256), interpolation=transforms.InterpolationMode.BILINEAR),
            transforms.ToTensor(),
            transforms.Normalize(mean=[0.5, 0.5, 0.5], std=[0.5, 0.5, 0.5]),
        ]
    )
    image = Image.open(path).convert("RGB")
    return transform(image).unsqueeze(0)


def compute_lpips_pairs(left_paths, right_paths, device):
    try:
        import lpips
    except ImportError as exc:
        raise RuntimeError("LPIPS requires the optional package `lpips`. Install it with: python -m pip install lpips") from exc

    pair_count = min(len(left_paths), len(right_paths))
    if pair_count == 0:
        raise ValueError("No paired images are available for LPIPS.")

    loss_fn = lpips.LPIPS(net="alex").to(device)
    scores = []
    with torch.no_grad():
        for left_path, right_path in zip(left_paths[:pair_count], right_paths[:pair_count]):
            left = pil_to_lpips_tensor(left_path).to(device)
            right = pil_to_lpips_tensor(right_path).to(device)
            score = loss_fn(left, right).item()
            scores.append(score)
    return {
        "pair_count": pair_count,
        "mean": float(np.mean(scores)),
        "std": float(np.std(scores)),
        "scores": [float(score) for score in scores],
    }


def build_report(results, output_dir):
    report_path = output_dir / "quality_metrics_report.md"
    lines = [
        "# FID / LPIPS 图像质量指标结果",
        "",
        "## 评价设置",
        "",
        f"- 真实参考图像目录：`{results['paths']['reference_dir']}`",
        f"- 未微调基础模型生成目录：`{results['paths']['base_dir']}`",
        f"- LoRA 微调模型生成目录：`{results['paths']['lora_dir']}`",
        f"- 设备：`{results['device']}`",
        "",
        "## 指标表",
        "",
        "| 指标 | 未微调 Stable Diffusion 基础模型 | LoRA 微调模型 | 判定方式 |",
        "| --- | --- | --- | --- |",
    ]

    fid = results.get("fid")
    if fid:
        base_fid = fid["base_vs_reference"]
        lora_fid = fid["lora_vs_reference"]
        better = "LoRA 更优" if lora_fid < base_fid else "基础模型更优"
        lines.append(f"| FID ↓ | {base_fid:.4f} | {lora_fid:.4f} | 数值越低，生成分布越接近真实水墨图像；本次结果：{better} |")

    lpips_result = results.get("lpips")
    if lpips_result:
        if "reference_vs_base" in lpips_result and "reference_vs_lora" in lpips_result:
            base_lpips = lpips_result["reference_vs_base"]["mean"]
            lora_lpips = lpips_result["reference_vs_lora"]["mean"]
            better = "LoRA 更接近配对参考图" if lora_lpips < base_lpips else "基础模型更接近配对参考图"
            lines.append(f"| LPIPS ↓ | {base_lpips:.4f} | {lora_lpips:.4f} | 成对图像感知距离越低越相似；本次结果：{better} |")
        elif "base_vs_lora" in lpips_result:
            mean_lpips = lpips_result["base_vs_lora"]["mean"]
            lines.append(
                f"| LPIPS(base, LoRA) | \\- | {mean_lpips:.4f} | 该值表示两组生成图的感知差异，不表示单独图像质量；数值越高说明 LoRA 改变越明显 |"
            )

    lines.extend(
        [
            "",
            "## 论文写作建议",
            "",
            "FID 用于衡量生成图像集合与真实图像集合在特征分布上的距离，数值越低表示生成结果越接近真实数据分布。"
            "因此，可将真实水墨数据集作为参考集，分别计算基础模型生成结果和 LoRA 微调模型生成结果的 FID。"
            "如果 LoRA 模型的 FID 低于基础模型，说明微调后生成图像在整体分布上更接近目标水墨风格数据。",
            "",
            "LPIPS 更适合用于成对图像之间的感知差异比较。若没有严格一一对应的真实目标图像，建议将 LPIPS 作为辅助指标，"
            "用于说明 LoRA 微调前后生成结果的感知差异，而不要单独把它解释为无参考图像质量分数。",
        ]
    )

    report_path.write_text("\n".join(lines), encoding="utf-8")
    return report_path


def main():
    args = parse_args()
    reference_dir = resolve_dir(args.reference_dir)
    base_dir = resolve_dir(args.base_dir)
    lora_dir = resolve_dir(args.lora_dir)
    output_dir = Path(args.output_dir).expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    reference_images = list_images(reference_dir)
    base_images = list_images(base_dir)
    lora_images = list_images(lora_dir)
    device = choose_device(args.device)

    results = {
        "device": str(device),
        "image_counts": {
            "reference": len(reference_images),
            "base": len(base_images),
            "lora": len(lora_images),
        },
        "paths": {
            "reference_dir": str(reference_dir),
            "base_dir": str(base_dir),
            "lora_dir": str(lora_dir),
        },
    }

    if not args.skip_fid:
        model = build_inception_model(device)
        reference_features = extract_inception_features(reference_images, model, device, args.batch_size)
        base_features = extract_inception_features(base_images, model, device, args.batch_size)
        lora_features = extract_inception_features(lora_images, model, device, args.batch_size)
        results["fid"] = {
            "base_vs_reference": calculate_fid(reference_features, base_features),
            "lora_vs_reference": calculate_fid(reference_features, lora_features),
        }

    if args.enable_lpips:
        if args.lpips_reference_dir:
            lpips_reference_dir = resolve_dir(args.lpips_reference_dir)
            lpips_reference_images = list_images(lpips_reference_dir)
            results["lpips"] = {
                "reference_vs_base": compute_lpips_pairs(lpips_reference_images, base_images, device),
                "reference_vs_lora": compute_lpips_pairs(lpips_reference_images, lora_images, device),
                "paired_reference_dir": str(lpips_reference_dir),
            }
        else:
            results["lpips"] = {
                "base_vs_lora": compute_lpips_pairs(base_images, lora_images, device),
            }

    result_path = output_dir / "quality_metrics_results.json"
    result_path.write_text(json.dumps(results, ensure_ascii=False, indent=2), encoding="utf-8")
    report_path = build_report(results, output_dir)

    print(
        json.dumps(
            {
                "status": "ok",
                "result_path": str(result_path),
                "report_path": str(report_path),
                "results": results,
            },
            ensure_ascii=False,
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
